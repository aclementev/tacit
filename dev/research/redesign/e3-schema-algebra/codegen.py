"""Tiny codegen prototype: derivation spec module -> real class definitions.

    uv run python codegen.py cg_spec            # writes cg_generated.py
    uv run python codegen.py cg_spec --check    # CI: exit 1 if cg_generated.py is stale

Emits, per derivation, (1) a Schema subclass with every column written out and
(2) a `<Name>Cols` TypedDict of ibis value types for `**Unpack[...]` builders.
Static types come from the class body; at runtime `__tacit_derived_from__`
lets tacit re-attach the source's Annotated constraints (checks, nullability).
"""

import argparse
import difflib
import importlib
import sys
from pathlib import Path
from typing import Annotated, Any, get_args, get_origin

from derive import Derivation

import datetime

IBIS_VALUE = {
    int: "ir.IntegerValue", float: "ir.FloatingValue", str: "ir.StringValue",
    bool: "ir.BooleanValue", datetime.datetime: "ir.TimestampValue", datetime.date: "ir.DateValue",
}


def type_src(t: Any, imports: set[str]) -> str:
    if get_origin(t) is Annotated:  # static type only; metadata comes from the source at runtime
        t = get_args(t)[0]
    if t.__module__ == "builtins":
        return t.__qualname__
    imports.add(f"import {t.__module__}")
    return f"{t.__module__}.{t.__qualname__}"


def ibis_src(t: Any) -> str:
    if get_origin(t) is Annotated:
        t = get_args(t)[0]
    return IBIS_VALUE.get(t, "ir.Value")


def spec_src(d: Derivation) -> str:
    base = d.base.__name__
    if d.op in ("pick", "drop"):
        args = ", ".join(repr(n) for n in d.names)
    elif d.op == "rename":
        args = ", ".join(f"{a}={b!r}" for a, b in d.renames)
    else:
        args = ", ".join(f"{k}={v.__qualname__}" for k, v in d.extra)
    return f"{d.op}({base}, {args})"


def generate(spec_module: str) -> str:
    mod = importlib.import_module(spec_module)
    derivations = [(n, v) for n, v in vars(mod).items() if isinstance(v, Derivation)]
    imports: set[str] = set()
    bases: set[tuple[str, str]] = set()
    body: list[str] = []
    for name, d in derivations:
        bases.add((d.base.__module__, d.base.__name__))
        cols = d.columns()
        # extend keeps nominal subtyping (IrisScored <: Iris); the others start fresh
        own = {k: v for k, v in d.extra} if d.op == "extend" else cols
        parent = d.base.__name__ if d.op == "extend" else "Schema"
        body.append(f"\n\nclass {name}({parent}):")
        body.append(f'    """Generated: {spec_src(d)}"""\n')
        body.append(f"    __tacit_derived_from__: ClassVar = {spec_src(d)}\n")
        body.extend(f"    {c}: {type_src(t, imports)}" for c, t in own.items())
        body.append(f"\n\nclass {name}Cols(TypedDict):")
        body.extend(f"    {c}: {ibis_src(t)}" for c, t in cols.items())
    header = [
        f"# GENERATED by codegen.py from {spec_module}.py. Do not edit; run `python codegen.py {spec_module}`.",
        "# ruff: noqa",
        "from typing import ClassVar, TypedDict",
        "",
        "import ibis.expr.types as ir",
        *sorted(imports),
        "from derive import drop, extend, pick, rename",
        "from tx import Schema",
        *[f"from {m} import {n}" for m, n in sorted(bases)],
    ]
    return "\n".join(header) + "\n" + "\n".join(body) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = Path(a.out or "cg_generated.py")
    new = generate(a.spec)
    if a.check:
        old = out.read_text() if out.exists() else ""
        if old != new:
            sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), new.splitlines(True), str(out), "regenerated"))
            print(f"\n{out} is stale: run `python codegen.py {a.spec}`", file=sys.stderr)
            return 1
        print(f"{out} is up to date")
        return 0
    out.write_text(new)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
