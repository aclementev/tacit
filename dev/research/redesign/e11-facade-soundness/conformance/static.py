"""Static side of the conformance harness: what each checker says for each case.

python static.py SRC_DIR OUT.json [checker ...]
  SRC_DIR: directory containing the `tacit_next` package whose _column.pyi is under test.

Generates gen/probe_*.py (one function per case, a single `reveal_type(<expr>)`
line each), runs pyright / mypy / ty / pyrefly with SRC_DIR on the search path,
and records per case: rejected (any error on the case line) and the revealed type.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent  # dev/research/redesign (uv project)
sys.path.insert(0, str(HERE))
from cases import all_cases  # noqa: E402

CHUNK = 1400
PRELUDE = """# ruff: noqa
# GENERATED by conformance/static.py
from datetime import date, datetime, time
from decimal import Decimal
from typing import reveal_type

from tacit_next import Column, Scalar

"""


def generate(gen: Path) -> dict[tuple[str, int], str]:
    gen.mkdir(exist_ok=True)
    for p in gen.glob("probe_*.py"):
        p.unlink()
    where: dict[tuple[str, int], str] = {}
    cases = all_cases()
    for k in range(0, len(cases), CHUNK):
        name = f"probe_{k // CHUNK:02d}.py"
        lines = PRELUDE.splitlines()
        for c in cases[k:k + CHUNK]:
            fam = c.fam
            lines.append(f"def {c.id}(x: {c.x_type}, y: Column[{fam}], yn: Column[{fam} | None]) -> None:")
            lines.append(f"    reveal_type({c.expr})")
            where[(name, len(lines))] = c.id
        (gen / name).write_text("\n".join(lines) + "\n")
    return where


def run(cmd: list[str], env: dict[str, str] | None = None) -> str:
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env={**os.environ, **(env or {})})
    return p.stdout + p.stderr


def norm(t: str) -> str:
    t = t.strip().strip('"`')
    t = re.sub(r"\b(tacit_next\._column|builtins|datetime|decimal|ibis\.expr\.types\.[a-z_]+|ibis\.expr\.types)\.", "", t)
    t = t.replace("_datetime", "datetime").replace("_date", "date").replace("_time", "time")
    t = t.replace("Union[", "U[").replace("NoneType", "None")
    return t


def checkers(src: Path, files: list[str], cfgdir: Path, want: set[str] | None = None) -> dict[str, list[tuple[str, int, str, str]]]:
    """-> {checker: [(file, line, 'reveal'|'error', text)]}"""
    cfgdir.mkdir(exist_ok=True)
    (cfgdir / "pyrightconfig.json").write_text(json.dumps({
        "pythonVersion": "3.13", "venvPath": str(ROOT), "venv": ".venv", "extraPaths": [str(src)],
        "typeCheckingMode": "standard", "reportMissingModuleSource": False}))
    (cfgdir / "mypy.ini").write_text(
        f"[mypy]\npython_version = 3.13\nfollow_untyped_imports = True\ncheck_untyped_defs = True\n"
        f"mypy_path = {src}\ncache_dir = {cfgdir}/.mypy_cache\n[mypy-tacit_next.*]\nignore_errors = True\n")
    (cfgdir / "pyrefly.toml").write_text(f'python-version = "3.13"\nsearch-path = ["{src}"]\n')
    out: dict[str, list[tuple[str, int, str, str]]] = defaultdict(list)
    want = want or {"pyright", "mypy", "ty", "pyrefly"}
    if "pyright" in want:
        raw = run(["uv", "run", "--frozen", "pyright", "-p", str(cfgdir / "pyrightconfig.json"), "--outputjson", *files])
        js = json.loads(raw[raw.index("{"):raw.rindex("}") + 1])
        for d in js["generalDiagnostics"]:
            f, ln = Path(d["file"]).name, d["range"]["start"]["line"] + 1
            m = re.match(r'Type of ".*" is "(.*)"$', d["message"], re.S)
            if d["severity"] == "information" and m:
                out["pyright"].append((f, ln, "reveal", norm(m.group(1))))
            elif d["severity"] == "error":
                out["pyright"].append((f, ln, "error", d["message"].splitlines()[0]))
    if "mypy" in want:
        raw = run(["uv", "run", "--frozen", "mypy", "--config-file", str(cfgdir / "mypy.ini"), *files])
        for line in raw.splitlines():
            m = re.match(r"(.*?\.py):(\d+): (error|note): (.*)", line)
            if not m:
                continue
            f, ln, sev, msg = Path(m.group(1)).name, int(m.group(2)), m.group(3), m.group(4)
            r = re.match(r'Revealed type is "(.*)"', msg)
            if r:
                out["mypy"].append((f, ln, "reveal", norm(r.group(1))))
            elif sev == "error":
                out["mypy"].append((f, ln, "error", msg))
    if "ty" in want:
        raw = run(["uv", "run", "--frozen", "ty", "check", "--python", ".venv", "--extra-search-path", str(src),
                   "--output-format", "concise", *files])
        for line in raw.splitlines():
            m = re.match(r"(.*?\.py):(\d+):\d+: (\w+)\[([\w-]+)\] (.*)", line)
            if not m:
                continue
            f, ln, sev, code, msg = Path(m.group(1)).name, int(m.group(2)), m.group(3), m.group(4), m.group(5)
            if code == "revealed-type":
                out["ty"].append((f, ln, "reveal", norm(msg.split("Revealed type: ", 1)[1])))
            elif sev == "error":
                out["ty"].append((f, ln, "error", f"[{code}] {msg}"))
    if "pyrefly" in want:
        raw = run(["uv", "run", "--frozen", "pyrefly", "check", "--python-interpreter-path", ".venv/bin/python",
                   "--config", str(cfgdir / "pyrefly.toml"), "--output-format", "min-text", *files])
        for line in raw.splitlines():
            m = re.match(r"\s*(?:ERROR |WARN )?(.*?\.py):(\d+):[\d-]+: (.*) \[([\w-]+)\]$", line)
            if not m:
                continue
            f, ln, msg, code = Path(m.group(1)).name, int(m.group(2)), m.group(3), m.group(4)
            if code == "reveal-type":
                out["pyrefly"].append((f, ln, "reveal", norm(msg.split("revealed type: ", 1)[1])))
            else:
                out["pyrefly"].append((f, ln, "error", f"[{code}] {msg}"))
    return out


def main(src: str, out_path: str) -> None:
    srcp = Path(src).resolve()
    tag = Path(out_path).stem
    gen = HERE / f"gen_{tag}"
    where = generate(gen)
    res = checkers(srcp, sorted(str(p) for p in gen.glob("probe_*.py")), HERE / f"cfg_{tag}", set(sys.argv[3:]))
    table: dict[str, dict[str, dict[str, object]]] = {}
    for chk, diags in res.items():
        per: dict[str, dict[str, object]] = {}
        for f, ln, kind, text in diags:
            cid = where.get((f, ln))
            if cid is None:
                continue
            e = per.setdefault(cid, {"rejected": False, "reveal": None, "errors": []})
            if kind == "reveal":
                e["reveal"] = text
            else:
                e["rejected"] = True
                e["errors"].append(text[:200])  # type: ignore[union-attr]
        table[chk] = per
        print(f"{chk}: {sum(v['rejected'] for v in per.values())} rejected / {len(per)} with output")
    Path(out_path).write_text(json.dumps(table, indent=0))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
