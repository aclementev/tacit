"""`tacit gen` prototype: emit `<module>.pyi` with per-schema Literal-keyed overloads.

    uv run --frozen python e14-column-refs/tools/tacit_gen.py path/to/schemas.py [--no-col]

The stub is the module's own source (a schema module holds schemas + imports, nothing
else) with two generated members inserted into every `tacit_r.Schema` subclass:

    @overload
    def __getitem__(self, key: Literal["amount"], /) -> Column[float]: ...   # df.c["amount"], df["amount"]
    @overload
    @classmethod
    def col(cls, key: Literal["amount"], /) -> Ref[Self, float]: ...        # Orders.col("amount")

Field names/types come from the RUNTIME classes (MRO-complete, so inheritance is free)
and are rendered from `get_type_hints`, so annotations are emitted with qualified names.
Checkers read the .pyi instead of the .py; at runtime nothing changes.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import sys
import types
import typing
from pathlib import Path
from typing import Any, get_args, get_origin


def alias(module: str) -> str:
    """aliased module imports: the stub keeps the source's own imports (e.g. `from datetime import datetime`)."""
    return "_g_" + module.replace(".", "_")


def fmt(t: Any, imports: set[str]) -> str:
    if t is None or t is type(None):
        return "None"
    if isinstance(t, types.UnionType) or get_origin(t) is typing.Union:
        return " | ".join(fmt(a, imports) for a in get_args(t))
    if get_origin(t) is typing.Annotated:
        return fmt(get_args(t)[0], imports)
    if (o := get_origin(t)) is not None:
        return f"{fmt(o, imports)}[{', '.join(fmt(a, imports) for a in get_args(t))}]"
    if isinstance(t, type):
        if t.__module__ == "builtins":
            return t.__qualname__
        imports.add(t.__module__)
        return f"{alias(t.__module__)}.{t.__qualname__}"
    raise TypeError(f"cannot render {t!r}")


def members(cls: type, imports: set[str], with_col: bool) -> list[str]:
    from tacit_r import Column

    hints = typing.get_type_hints(cls, include_extras=True)
    out: list[str] = []
    rows = []
    for attr in cls.__tacit_fields__:  # type: ignore[attr-defined]
        h = hints[attr]
        if get_origin(h) is typing.Annotated:
            h = get_args(h)[0]
        assert get_origin(h) is Column, (cls, attr, h)
        (vt,) = get_args(h)
        rows.append((attr, fmt(h, imports), fmt(vt, imports)))
    for attr, col_t, _ in rows:
        out += ["    @overload", f'    def __getitem__(self, key: Literal["{attr}"], /) -> {col_t}: ...']
    if with_col:
        for attr, _, vt in rows:
            out += ["    @overload", "    @classmethod", f'    def col(cls, key: Literal["{attr}"], /) -> Ref[Self, {vt}]: ...']
    if len(rows) == 1:  # a single overload is invalid: emit plain methods
        out = [ln for ln in out if ln.strip() != "@overload"]
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("module", type=Path)
    ap.add_argument("--no-col", action="store_true")
    a = ap.parse_args()
    path: Path = a.module.resolve()
    sys.path.insert(0, str(path.parent))
    spec = importlib.util.spec_from_file_location(path.stem, path)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[path.stem] = mod
    spec.loader.exec_module(mod)
    from tacit_r import Schema

    src = path.read_text().splitlines()
    tree = ast.parse("\n".join(src))
    imports: set[str] = set()
    inserts: list[tuple[int, list[str]]] = []
    n = 0
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            cls = getattr(mod, node.name, None)
            if isinstance(cls, type) and issubclass(cls, Schema) and cls is not Schema:
                body = members(cls, imports, not a.no_col)
                inserts.append((node.end_lineno or node.lineno, body))
                n += 1
    for end, body in sorted(inserts, reverse=True):
        src[end:end] = body
    header = [
        f"# GENERATED by e14 tools/tacit_gen.py from {path.name} -- do not edit; re-run after changing schemas.",
        "from typing import Literal, Self, overload",
        "from tacit_r import Ref",
        *sorted(f"import {m} as {alias(m)}" for m in imports),
    ]
    out = path.with_suffix(".pyi")
    out.write_text("\n".join(header + src) + "\n")
    print(f"wrote {out}: {n} schemas, {sum(b.count('    @overload') for _, b in inserts)} overloads")


if __name__ == "__main__":
    main()
