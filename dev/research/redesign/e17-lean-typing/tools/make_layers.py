"""Assemble the three typing layers from one common source tree.

    uv run --frozen python e17-lean-typing/tools/make_layers.py

layers/<L>/tacit_thin + tacit_t2  = src_common/ (E13 tacit_thin + tacit_t2, plus a T2 join)
                                    with the layer's column typing swapped in:
    l1: overlays/l1/tacit_thin/_column.pyi            (hand-written, ~55 lines)
    l2: overlays/l2/tacit_thin/_column.pyi + _ibis_cols.pyi (generated by tools/gen_cols_stub.py)
    l3: e11-facade-soundness/derived/out_ibis/tacit_next/_column.pyi (the E11 derived facade)
layers/<L>/tacit_t2n = tacit_t2 whose DataFrame statically subclasses ir.Table (NO Table stub).
"""

from __future__ import annotations

import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
COMMON = HERE / "src_common"
E11 = HERE.parent / "e11-facade-soundness" / "derived" / "out_ibis" / "tacit_next" / "_column.pyi"


def main() -> None:
    out = HERE / "layers"
    shutil.rmtree(out, ignore_errors=True)
    for layer in ("l1", "l2", "l3"):
        dst = out / layer
        shutil.copytree(COMMON, dst, ignore=shutil.ignore_patterns("__pycache__"))
        ov = HERE / "overlays" / layer
        if ov.exists():
            shutil.copytree(ov, dst, dirs_exist_ok=True)
        if layer == "l3":
            text = E11.read_text() + "\n\n# E17: handle-parameter spellings\nAnyCol = Column[Any]\nTsCol = Column[_datetime]\n"
            (dst / "tacit_thin" / "_column.pyi").write_text(text)
        n = dst / "tacit_t2n"
        shutil.copytree(dst / "tacit_t2", n)
        df = (n / "_df.py").read_text()
        old = "from tacit_thin._ibis_api import TableAPI as _TableBase"
        assert old in df
        (n / "_df.py").write_text(df.replace(old, "from ibis.expr.types import Table as _TableBase  # no Table stub"))
        print(f"built {dst}")


if __name__ == "__main__":
    main()
