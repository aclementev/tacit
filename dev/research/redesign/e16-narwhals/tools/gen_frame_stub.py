"""Generate tacit_nw's static frame base from narwhals' own LazyFrame signatures.

narwhals is typed, and its frames have no `__getattr__`, so (unlike ibis, E13) nothing needs
removing. The one problem is that every schema-changing method returns `Self`: a subclass
`DataFrame[S]` would keep claiming schema S after `with_columns(...)`/`select(...)`/`join(...)`
(forgot-cast undetectable). This script copies the signatures of the schema-changing methods
(overloads included) from narwhals' source via `ast`, rewrites `Self` -> `LazyFrame[Any]`, and
emits `class LazyFrameAPI(LazyFrame[Any])` as a .pyi. Schema-preserving methods keep `Self`.

usage: uv run python tools/gen_frame_stub.py  -> src/tacit_nw/_lazy_api.pyi (+ report on stdout)
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import narwhals
import narwhals.stable.v2 as nw

SRC = Path(narwhals.__file__).parent / "dataframe.py"
OUT = Path(__file__).resolve().parents[1] / "src" / "tacit_nw" / "_lazy_api.pyi"

# schema-preserving: same columns, same dtypes (row subset / reorder)
PRESERVING = {"filter", "sort", "head", "tail", "unique", "drop_nulls", "top_k", "gather_every", "lazy"}


def module_imports(tree: ast.Module) -> dict[str, str]:
    """name -> 'from X import Y [as name]' for every import in the module (TYPE_CHECKING blocks included)."""
    out: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            for a in node.names:
                nm = a.asname or a.name
                out[nm] = f"from {node.module} import {a.name}" + (f" as {a.asname}" if a.asname else "")
        elif isinstance(node, ast.Import):
            for a in node.names:
                nm = a.asname or a.name.split(".")[0]
                out[nm] = f"import {a.name}" + (f" as {a.asname}" if a.asname else "")
    return out


def main() -> None:
    tree = ast.parse(SRC.read_text())
    imports = module_imports(tree)
    classes = {n.name: n for n in tree.body if isinstance(n, ast.ClassDef)}
    lazy, base = classes["LazyFrame"], classes["BaseFrame"]

    def defs(cls: ast.ClassDef, name: str) -> list[ast.FunctionDef]:
        return [n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == name]

    public = sorted({n.name for c in (lazy, base) for n in c.body if isinstance(n, ast.FunctionDef) and not n.name.startswith("_")})
    # runtime truth: what v2 LazyFrame exposes and which of those return Self
    members = [m for m in public if hasattr(nw.LazyFrame, m)]
    changing, preserving, other = [], [], []
    body: list[str] = []
    used: set[str] = set()
    for m in members:
        fns = defs(lazy, m) or defs(base, m)
        if not fns:
            continue
        ret_src = ast.unparse(fns[-1].returns) if fns[-1].returns else ""
        if "Self" not in ret_src:
            other.append(m)
            continue
        if m in PRESERVING:
            preserving.append(m)
            continue
        changing.append(m)
        for fn in fns:
            is_overload = any(ast.unparse(d) == "overload" for d in fn.decorator_list)
            if len(fns) > 1 and not is_overload:
                continue  # the implementation signature of an overloaded method
            fn2 = ast.FunctionDef(name=fn.name, args=fn.args, body=[ast.Expr(ast.Constant(...))],
                                  decorator_list=[d for d in fn.decorator_list if ast.unparse(d) == "overload"],
                                  returns=fn.returns, type_params=[], lineno=fn.lineno)
            txt = ast.unparse(fn2)
            # Self -> LazyFrame[Any] in the return AND in parameters (join(other: Self) must accept any frame)
            txt = re.sub(r"\bSelf\b", "LazyFrame[Any]", txt)
            head, _, ret = txt.rpartition(") -> ")
            txt = txt.replace(":\n    ...", ": ...  # type: ignore[override]")
            used |= set(re.findall(r"\b[A-Za-z_][A-Za-z0-9_]*\b", head.split("(", 1)[1] + " " + ret))
            body.append("\n".join("    " + line for line in txt.splitlines()))
    lines = ["# GENERATED by tools/gen_frame_stub.py from narwhals " + narwhals.__version__ + " -- do not edit.",
             '"""Static base of tacit_nw.DataFrame: narwhals LazyFrame with schema-changing methods returning a plain LazyFrame."""',
             "", "from typing import Any, overload", ""]
    skip = {"self", "Any", "None", "True", "False", "overload", "LazyFrame", "str", "int", "bool", "float", "list", "tuple", "dict", "type", "object"}
    missing = []
    for nm in sorted(used - skip):
        if nm in imports:
            lines.append(imports[nm])
        elif nm not in {"Self"} and not nm.islower():
            missing.append(nm)
    lines += ["from narwhals.stable.v2 import LazyFrame", "", "", "class LazyFrameAPI(LazyFrame[Any]):"]
    lines += body
    OUT.write_text("\n".join(lines) + "\n")
    print(f"narwhals {narwhals.__version__}: {len(members)} public LazyFrame members")
    print(f"  schema-changing, rewritten to LazyFrame[Any] ({len(changing)}): {', '.join(changing)}")
    print(f"  schema-preserving, keep Self ({len(preserving)}): {', '.join(preserving)}")
    print(f"  other (no Self in return) ({len(other)}): {', '.join(other)}")
    print(f"  unresolved names: {missing or 'none'}")
    print(f"  wrote {OUT.relative_to(OUT.parents[2])} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
