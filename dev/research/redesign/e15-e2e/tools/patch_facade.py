"""Copy E11's derived facade (fallback=ibis) into tacit_t3 and apply the E15 hand rules.

    uv run --frozen python e15-e2e/tools/patch_facade.py [FACADE.pyi]

Facade-agnostic: the facade is the ONLY static file tacit_t3 takes from outside (`_column.pyi`;
every module imports Column/Scalar from `._column`). Pass any facade .pyi (e.g. E17's lean one)
that defines `class Column(...)` / `class Scalar(...)` and the module-level `lit`, `cases`,
`row_number`, `as_ibis`, `as_column`; the two rules below are applied by anchoring on the class
docstrings, so a different facade needs those anchors adjusted (asserted below).

Rules added on top of the generated stub (each is a small, documented hand-table entry):
* `assume_not_null()` on Column / Scalar: `Column[T | None] -> Column[T]` (runtime: a checked
  marker, verified when an output frame is constructed; see tacit_t3/_column.py).
* `tacit.cases` branch conditions accept `Column[bool | None]` (SQL CASE treats NULL as false),
  matching filter / join predicates.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
import sys

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "e11-facade-soundness" / "derived" / "out_ibis" / "tacit_next" / "_column.pyi"
DST = HERE / "src" / "tacit_t3" / "_column.pyi"

s = SRC.read_text()
s = s.replace("# GENERATED by e11 derived/gen_derived.py", "# GENERATED by e11 derived/gen_derived.py (+ e15 tools/patch_facade.py rules)", 1)
s = s.replace("tacit_next columns", "tacit_t3 columns", 1)
col_anchor = '    """A typed column (DERIVED facade: generated from ibis 12.0.0 + small hand tables)."""\n'
assert col_anchor in s
s = s.replace(col_anchor, col_anchor +
    "    def assume_not_null(self: Column[V | None]) -> Column[V]:\n"
    '        """Narrow `Column[T | None]` to `Column[T]`; checked (one null count) when the output is built."""\n', 1)
sc_anchor = '    """A typed scalar (DERIVED facade)."""\n'
assert sc_anchor in s
s = s.replace(sc_anchor, sc_anchor +
    "    def assume_not_null(self: Scalar[V | None]) -> Scalar[V]:\n"
    '        """Narrow `Scalar[T | None]` to `Scalar[T]`; checked when the output is built."""\n', 1)
old = "def cases(*branches: tuple[Column[bool] | Scalar[bool], "
assert old in s
s = s.replace(old, "def cases(*branches: tuple[Column[bool | None] | Scalar[bool | None], ", 1)
DST.write_text(s)
print(f"wrote {DST} ({len(s.splitlines())} lines)")
