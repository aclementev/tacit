"""Generate src/tacit_next/_column.pyi: the static-only facade for Column[T] / Scalar[T].

The facade exists only for type checkers. At runtime a column is the plain ibis
expression (see _column.py). Operators need one overload per value family
(int / float / Decimal / str / date, each non-null and nullable), so they are
generated instead of hand-written. Methods whose result type does not depend
on nullability use self-type restrictions over the nullable family
(`self: Column[float | None]` also accepts `Column[int]`, `Column[float]` via
covariance + int->float promotion).

Run: python tools/gen_facade.py   (rewrites the .pyi)
"""

from __future__ import annotations

import re
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "tacit_next" / "_column.pyi"

# Library-internal suppressions. The facade deliberately narrows/changes ibis
# signatures (Liskov "violations" vs ir.Value) and declares overlapping
# overloads; users never see these because checkers don't report library files.
IGN = "  # type: ignore"

HEADER = '''\
# GENERATED by tools/gen_facade.py -- do not edit by hand.
"""Static facade for tacit_next columns (type checkers only).

`Column[T]` / `Scalar[T]` are what checkers see for `frame.col` and for
reductions. At runtime the same values are plain ibis expressions.
"""

from collections.abc import Iterable, Sequence
from datetime import date as _date, datetime as _datetime, time as _time  # aliased: Column.date() shadows `date` in the class body
from decimal import Decimal
from typing import Any, Generic, Literal, Self, TypeVar, overload

import ibis.expr.datatypes as dt
import ibis.expr.types as ir
from ibis.expr.types.relations import Table

T_co = TypeVar("T_co", covariant=True)
V = TypeVar("V")
U = TypeVar("U")

type DataTypeLike = str | dt.DataType
'''

# (self element type, accepted literal(s), accepted expr element types, result for + - * // %, result for /)
ARITH = [
    ("int", "int", ["int"], "int", "float"),
    ("float", "float", ["float"], "float", "float"),
    ("Decimal", "int | Decimal", ["Decimal", "int"], "Decimal", "Decimal"),
    ("int | None", "int | None", ["int | None"], "int | None", "float | None"),
    ("float | None", "float | None", ["float | None"], "float | None", "float | None"),
    ("Decimal | None", "int | Decimal | None", ["Decimal | None", "int | None"], "Decimal | None", "Decimal | None"),
]
STR_CONCAT = [("str", "str", ["str"], "str"), ("str | None", "str | None", ["str | None"], "str | None")]
ARITH_OPS = ["add", "sub", "mul", "truediv", "floordiv", "mod"]

# comparisons: (self family, literal types, expr element types)
CMP = [
    ("float | None", "float", ["float | None"]),
    ("Decimal | None", "int | Decimal", ["Decimal | None", "int | None"]),
    ("str | None", "str", ["str | None"]),
    ("date | None", "date | str", ["date | None"]),
    ("time | None", "time | str", ["time | None"]),
]
CMP_OPS = ["lt", "le", "gt", "ge"]
EQ_OPS = ["eq", "ne"]
BOOL_OPS = ["and", "or", "xor"]


def exprs(container: str, elems: list[str]) -> str:
    return " | ".join(f"{container}[{e}]" for e in elems)


def col_arith() -> list[str]:
    out: list[str] = []
    for op in ARITH_OPS:
        for name in (f"__{op}__", f"__r{op}__"):
            out.append("    @overload")
            rows = [(s, lit, ex, (div if op == "truediv" else res)) for s, lit, ex, res, div in ARITH]
            if op == "add":
                rows += STR_CONCAT
            for i, (s, lit, ex, res) in enumerate(rows):
                if i:
                    out.append("    @overload")
                other = f"{lit} | {exprs('Column', ex)} | {exprs('Scalar', ex)}"
                out.append(f"    def {name}(self: Column[{s}], other: {other}, /) -> Column[{res}]: ...{IGN}")
    return out


def scalar_arith() -> list[str]:
    out: list[str] = []
    for op in ARITH_OPS:
        for name in (f"__{op}__", f"__r{op}__"):
            rows = [(s, lit, ex, (div if op == "truediv" else res)) for s, lit, ex, res, div in ARITH]
            if op == "add":
                rows += STR_CONCAT
            for s, lit, ex, res in rows:
                out.append("    @overload")
                out.append(
                    f"    def {name}(self: Scalar[{s}], other: {lit} | {exprs('Scalar', ex)}, /) -> Scalar[{res}]: ...{IGN}"
                )
                out.append("    @overload")
                out.append(f"    def {name}(self: Scalar[{s}], other: {exprs('Column', ex)}, /) -> Column[{res}]: ...{IGN}")
    return out


def comparisons(container: str) -> list[str]:
    out: list[str] = []
    for op in CMP_OPS + EQ_OPS:
        for s, lit, ex in CMP:
            if container == "Column":
                other = f"{lit} | {exprs('Column', ex)} | {exprs('Scalar', ex)}"
                out.append("    @overload")
                out.append(f"    def __{op}__(self: Column[{s}], other: {other}, /) -> Column[bool]: ...{IGN}")
            else:
                out.append("    @overload")
                out.append(
                    f"    def __{op}__(self: Scalar[{s}], other: {lit} | {exprs('Scalar', ex)}, /) -> Scalar[bool]: ...{IGN}"
                )
                out.append("    @overload")
                out.append(f"    def __{op}__(self: Scalar[{s}], other: {exprs('Column', ex)}, /) -> Column[bool]: ...{IGN}")
    return out


def bool_ops(container: str) -> list[str]:
    out: list[str] = []
    other = "bool | Column[bool | None] | Scalar[bool | None]" if container == "Column" else "bool | Scalar[bool | None]"
    res = "Column[bool]" if container == "Column" else "Scalar[bool]"
    for op in BOOL_OPS:
        for name in (f"__{op}__", f"__r{op}__"):
            out.append(f"    def {name}(self: {container}[bool | None], other: {other}, /) -> {res}: ...{IGN}")
    out += preserving(container, "__invert__", "", ["bool"])
    out += preserving(container, "__neg__", "", NUMERIC)
    return out


