# Families in overload order (bool <: int <: float; datetime <: date).
ALL = ["bool", "int", "float", "Decimal", "str", "datetime", "date", "time"]
NUMERIC = ["int", "float", "Decimal"]


def preserving(container: str, name: str, params: str, fams: list[str], ret: str | None = None) -> list[str]:
    """Overloads that keep the element type and its nullability: (Column[X]) -> Column[X], (Column[X | None]) -> ...

    Explicit per-family overloads instead of one bounded TypeVar (`self: Column[N]`):
    mypy does not check a TypeVar's bound when binding `self`, so `o.status.abs()` slipped through.
    """
    out: list[str] = []
    for f in fams:
        for nn in (f, f"{f} | None"):
            r = (ret or "{X}").replace("{X}", nn)
            out.append("    @overload")
            out.append(f"    def {name}(self: {container}[{nn}]{params}) -> {container}[{r}]: ...{IGN}")
    return out


def per_family(container: str, template: str, fams: list[str]) -> list[str]:
    """One overload per family; `{X}` is the element type (self is always the nullable family)."""
    out: list[str] = []
    for f in fams:
        out.append("    @overload")
        out.append("    " + template.replace("{C}", container).replace("{X}", f) + IGN)
    return out


LIT_CASTS = [
    ("int", '"int8", "int16", "int32", "int64", "uint8", "uint16", "uint32", "uint64"'),
    ("float", '"float32", "float64", "double"'),
    ("str", '"string", "str"'),
    ("bool", '"boolean", "bool"'),
    ("date", '"date"'),
    ("datetime", '"timestamp"'),
]


def cast_overloads(container: str) -> list[str]:
    """cast/try_cast: a Python type, a dtype string literal ("float64"), or any other dtype (-> Any)."""
    out: list[str] = []
    for name, nullable in (("cast", False), ("try_cast", True)):
        if container == "Scalar" and name == "try_cast":
            continue
        opt = " | None" if nullable else ""
        out += ["    @overload", f"    def {name}(self, target: type[U], /) -> {container}[U{opt}]: ...{IGN}"]
        for py, lit in LIT_CASTS:
            out += ["    @overload", f"    def {name}(self, target: Literal[{lit}], /) -> {container}[{py}{opt}]: ...{IGN}"]
        out += ["    @overload", f"    def {name}(self, target: DataTypeLike, /) -> {container}[Any]: ...{IGN}"]
    return out


def column_methods() -> list[str]:
    out: list[str] = ["", "    # -- per-family methods (generated)"] + cast_overloads("Column")
    out += per_family("Column", "def fill_null(self: {C}[{X} | None], value: {X} | Column[{X}] | Scalar[{X}], /) -> {C}[{X}]: ...", ALL)
    out += per_family("Column", "def isin(self: {C}[{X} | None], values: Sequence[{X}] | Column[{X} | None], /) -> Column[bool]: ...", ALL)
    out += per_family("Column", "def notin(self: {C}[{X} | None], values: Sequence[{X}] | Column[{X} | None], /) -> Column[bool]: ...", ALL)
    out += per_family(
        "Column",
        "def between(self: {C}[{X} | None], lower: {X} | Scalar[{X}], upper: {X} | Scalar[{X}], /) -> Column[bool]: ...",
        ["int", "float", "Decimal", "str", "datetime", "date"],
    )
    out += preserving("Column", "abs", "", NUMERIC)
    out += preserving("Column", "clip", ", lower: float | None = None, upper: float | None = None", NUMERIC)
    out += [
        "    @overload",
        f"    def round(self: Column[float], digits: None = None) -> Column[int]: ...{IGN}",
        "    @overload",
        f"    def round(self: Column[float | None], digits: None = None) -> Column[int | None]: ...{IGN}",
    ]
    out += preserving("Column", "round", ", digits: int", NUMERIC)
    for name, params in [
        ("upper", ""),
        ("lower", ""),
        ("strip", ""),
        ("replace", ", pattern: str, replacement: str, /"),
        ("substr", ", start: int, length: int | None = None"),
        ("re_extract", ", pattern: str, index: int"),
    ]:
        out += preserving("Column", name, params, ["str"])
    out += preserving("Column", "truncate", ", unit: str, /", ["datetime", "date"])
    return out


def scalar_methods() -> list[str]:
    return cast_overloads("Scalar") + per_family("Scalar", "def fill_null(self: {C}[{X} | None], value: {X} | Scalar[{X}], /) -> {C}[{X}]: ...", ALL)


def main() -> None:
    lines = [HEADER, COLUMN_BODY.replace("{IGN}", IGN)]
    lines += column_methods() + col_arith() + comparisons("Column") + bool_ops("Column")
    lines.append(SCALAR_BODY.replace("{IGN}", IGN))
    lines += scalar_methods() + scalar_arith() + comparisons("Scalar") + bool_ops("Scalar")
    lines.append(FUNCS)
    text = "\n".join(lines) + "\n"
    # `Column.date()` would shadow the `date` type inside the class body: use aliases.
    head, sep, body = text.partition("import ibis.expr.datatypes as dt")
    body = re.sub(r"(?<![\w.])datetime\b", "_datetime", body)
    body = re.sub(r"(?<![\w.])date(?=[\] |,)])", "_date", body)
    body = re.sub(r"(?<![\w.])time(?=[\] |,)])", "_time", body)
    OUT.write_text(head + sep + body)
    print(f"wrote {OUT} ({sum(s.count(chr(10)) + 1 for s in lines)} lines)")


if __name__ == "__main__":
    main()
